/**
 * Recursively list all files under `dir`, returning POSIX-style paths
 * relative to `dir` (no leading separator, forward slashes).
 * Replacement for the `glob` npm package using Node's built-in fs.
 */
async function listFilesRecursive(dir) {
    const entries = await fs.promises.readdir(dir, {
        recursive: true,
        withFileTypes: true,
    });
    const results = [];
    for (const entry of entries) {
        if (!entry.isFile()) continue;
        const parentDir = entry.parentPath ?? entry.path;
        const abs = path.join(parentDir, entry.name);
        const rel = path.relative(dir, abs).split(path.sep).join("/");
        results.push(rel);
    }
    return results;
}

